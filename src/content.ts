/** Western digits → Persian digits, with the Persian thousands separator. */
export function fa(n: number | string, group = true): string {
  const s = typeof n === 'number' ? (group ? Math.round(n).toLocaleString('en-US') : String(Math.round(n))) : n;
  return s.replace(/[0-9]/g, (d) => '۰۱۲۳۴۵۶۷۸۹'[+d]).replace(/,/g, '٬');
}
